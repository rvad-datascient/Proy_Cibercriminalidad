# ==============================================================================
# Utilidades de Evaluación de Modelos
# ==============================================================================

import numpy as np
import pandas as pd
from sklearn.metrics import mean_absolute_error, r2_score

# ---------------------------------------------------------
# MÉTRICA WAPE
# ---------------------------------------------------------
def calcular_wape(y_true, y_pred):
    """
    Calcula el Error Porcentual Medio Ponderado (WAPE).
    """
    return (np.sum(np.abs(y_true - y_pred)) / np.sum(y_true)) * 100


# ---------------------------------------------------------
# MÉTRICAS BÁSICAS (MAE, R2, WAPE)
# ---------------------------------------------------------
def evaluar_modelo(y_true, y_pred):
    """
    Devuelve un diccionario con MAE, R2 y WAPE.
    """
    return {
        "MAE": mean_absolute_error(y_true, y_pred),
        "R2": r2_score(y_true, y_pred),
        "WAPE": calcular_wape(y_true, y_pred)
    }


# ---------------------------------------------------------
# TABLA DE RESULTADOS
# ---------------------------------------------------------
def tabla_resultados(lista_resultados):
    """
    Convierte una lista de diccionarios en un DataFrame ordenado.
    """
    df = pd.DataFrame(lista_resultados)
    return df.sort_values(by=["Dataset", "WAPE"])