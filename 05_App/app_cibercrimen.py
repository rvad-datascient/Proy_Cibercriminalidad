def formato_es(x):
    return f"{x:,.0f}".replace(",", ".")

# Función para la visualización de los graficos evolutivos
def plot_evolucion(df_plot, title, y_label, color_real, color_pred):
    # 1. Preparación de datos
    df_plot = df_plot.copy()
    
    # Crear la columna formateada con punto para miles
    # El formato :.0f asegura que no haya decimales y use punto como separador
    df_plot["Total_Hechos_Str"] = df_plot["Total_Hechos"].apply(lambda x: f"{int(x):,}".replace(",", "."))
    
    df_plot["periodo"] = df_plot["periodo"].astype(str)
    df_plot = df_plot.sort_values("periodo")
    
    fig = go.Figure()

    # 2. Separamos datos para las trazas
    real = df_plot[df_plot["Tipo_periodo"] == "Real"]
    pred = df_plot[df_plot["Tipo_periodo"] == "Predicción"]

    # 3. Traza REAL
    fig.add_trace(go.Scatter(
        x=real["periodo"], 
        y=real["Total_Hechos"],
        customdata=real["Total_Hechos_Str"],
        mode="lines+markers", 
        name="Real (2022–2024)",
        line=dict(color=color_real, width=3),
        hovertemplate="%{customdata}<extra></extra>"
    ))

    # 4. Traza PREDICCIÓN (Forzamos la unión con el último punto real)
    last_real = real.iloc[-1:] 
    pred_con_conexion = pd.concat([last_real, pred])

    fig.add_trace(go.Scatter(
        x=pred_con_conexion["periodo"], 
        y=pred_con_conexion["Total_Hechos"],
        customdata=pred_con_conexion["Total_Hechos_Str"],
        mode="lines+markers", 
        name="Predicción 2025",
        line=dict(color=color_pred, width=3, dash="dash"),
        hovertemplate="%{customdata}<extra></extra>"
    ))

    # 5. Ajustes finales
    fig.update_xaxes(type='category')
    fig.update_layout(
        title=title, 
        xaxis_title="Año", 
        yaxis=dict(
            title=y_label,
            # Forzamos los ticks del eje Y para que coincidan con nuestro formato
            tickformat=".,.0f" 
        ),
        showlegend=True,
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
        hovermode="x unified"
    )
    
    return fig

#Funciòn para los mapas mueve Canarias para que se visualice mejor el mapa
def mover_canarias(geojson, dx=5.5, dy=4.5, scale=1.0):
    canarias = ["35", "38"]

    for feature in geojson["features"]:
        cod = feature["properties"]["cod_prov"]
        geom = feature["geometry"]

        if cod in canarias:
            if geom["type"] == "Polygon":
                geom["coordinates"] = [
                    [[lon * scale + dx, lat * scale + dy] for lon, lat in ring]
                    for ring in geom["coordinates"]
                ]

            elif geom["type"] == "MultiPolygon":
                geom["coordinates"] = [
                    [
                        [[lon * scale + dx, lat * scale + dy] for lon, lat in ring]
                        for ring in poly
                    ]
                    for poly in geom["coordinates"]
                ]

    return geojson

