# @st.cache_data es un decorador de Python que almacena en caché el resultado
# de la función. Esto evita que Streamlit vuelva a procesar datos pesados
# (como leer CSVs o GeoJSONs) en cada interacción del usuario, optimizando
# drásticamente el rendimiento y la velocidad de carga de la App.

@st.cache_data
def load_data():
    # 1. Defino las rutas según la estructura del proyecto usando os.path.join
    process_dir = os.path.join(root_dir, "01_Data", "Process")
    pred_dir = os.path.join(root_dir, "01_Data", "Predictions")

    # 2. Rutas específicas a los archivos
    path_real = os.path.join(process_dir, "df_cibercrimen.csv")
    path_pred = os.path.join(pred_dir, "df_cibercrimen_predicciones_2025.csv")

    # 3. Validación de seguridad: comprubeo si los archivos existen antes de leer.
    # st.stop() es clave: detiene el script evitando errores en cascada (FileNotFoundError).
    for path in [path_real, path_pred]:
        if not os.path.exists(path):
            st.error(f"Error crítico: No se encuentra el archivo en la ruta: {path}")
            st.stop()

    # 4. Carga de los datos una vez confirmada su existencia
    df_real = pd.read_csv(path_real, sep=";")
    df_pred = pd.read_csv(path_pred, sep=";")

    # 5. Normalización: Limpio espacios y paso a minúsculas para asegurar
    # que los merges o filtros no fallen por diferencias de formato (ej: 'Madrid' vs 'madrid')
    for df in [df_real, df_pred]:
        df["Provincias"] = df["Provincias"].str.strip().str.lower()
        # Limpieza de código INE para asegurar formato "02", "03"...
        df["codigo_ine"] = df["codigo_ine"].astype(str).str.replace(r'\.0$', '', regex=True)
        df["codigo_ine"] = df["codigo_ine"].str.zfill(2)
        # Forzamos a object para que sea el tipo de dato que espera Plotly
        df["codigo_ine"] = df["codigo_ine"].astype(object)

    # 6. Etiquetado: Marco el origen de los datos para diferenciarlos en los gráficos
    df_real["Tipo_periodo"] = "Real"
    df_pred["Tipo_periodo"] = "Predicción"

    # 7. Unificación: Concateno ambos datasets en uno solo (DataFrame largo)
    # y transformo 'periodo' a string para evitar los ejes con decimales
    
    # Aseguramos nombres consistentes antes del concat
    df_real = df_real.rename(columns={'Provincias': 'Provincias'})
    df_pred = df_pred.rename(columns={'Provincias': 'Provincias'})
    
    df = pd.concat([df_real, df_pred], ignore_index=True)
    
    # IMPORTANTE: Convertimos a String para que Plotly trate los años como categorías
    df["periodo"] = df["periodo"].astype(str)

    return df


@st.cache_data
def load_geojson():
    # === VALIDACIÓN GEOJSON ===
    process_dir = os.path.join(root_dir, "01_Data", "Process")
    path_geo = os.path.join(process_dir, "spain-provinces.geojson")

    if not os.path.exists(path_geo):
        st.error(f"Error crítico: Falta el archivo de mapas en {path_geo}")
        st.stop()

    # Carga del JSON de provincias
    with open(path_geo, "r", encoding="utf-8") as f:
        geo_data = json.load(f)

# FORZAR: Asegurar que todos los IDs en el GeoJSON sean strings de 2 dígitos
    for feature in geo_data["features"]:
        cod = str(feature["properties"].get("cod_prov", ""))
        feature["properties"]["cod_prov"] = cod.zfill(2)

    return mover_canarias(geo_data)

